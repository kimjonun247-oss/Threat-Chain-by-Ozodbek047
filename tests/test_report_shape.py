"""Freeze today's report shapes so the next eight phases cannot change them quietly.

Every phase in REJA.md adds fields to these reports. The rule that makes those
additions safe is "only add, never rename or remove", and this file is what
enforces it. Three layers, weakest first:

  1. A snapshot of every key path and its type across the frozen fixtures. Any
     drift -- a renamed key, a value that turns from str to dict -- fails loudly
     and has to be either undone or explicitly re-frozen.
  2. An explicit per-stage contract (REQUIRED below) naming the fields the API
     and the browser actually read. This one is written out by hand because a
     snapshot diff says *what* changed and this says *why it matters*.
  3. The real consumers -- markdown export, SARIF export, the verification
     summary -- run against every frozen report. This is the layer that catches
     "the new code assumes a field the old reports never had", which no amount of
     key comparison would find.
  4. One live scan, compared against its frozen counterpart. Layers 1-3 read
     static files, so on their own they would pass while the code that *writes*
     reports drifted away from them. The repository scanner is the one that runs
     in milliseconds with no external tool, so it is the one run for real here.

Fixtures come from tests/fixtures/legacy/ and are regenerated by
tests/make_legacy_fixtures.py; see its docstring for what was redacted.
"""
import json
import shutil
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

from zanjir import dependencies, pipeline, repo_store, repository, verification, webscan
from isolation import isolate_triage

FIXTURES = Path(__file__).resolve().parent / 'fixtures/legacy'
SNAPSHOT = Path(__file__).resolve().parent / 'fixtures/shape-snapshot.json'

# Fields the API serves and dist/*.js reads by name. Losing one of these breaks
# a screen; the comment on each line says which.
REQUIRED = {
    'code': {'id', 'target', 'created_at', 'state', 'count',      # history rows + scanners.js
             'findings', 'tools', 'limits'},
    'dependencies': {'id', 'target', 'created_at', 'state', 'count',
                     'findings', 'limits', 'inventory_sha256'},   # inventory_sha256 keys the reviews file
    'images': {'id', 'target', 'created_at', 'state', 'count',
               'reference', 'limits'},                            # pilot-dashboard.js render()
    'web': {'id', 'target', 'created_at', 'state', 'count', 'findings', 'limits'},
    'repository': {'id', 'profile_id', 'created_at', 'findings',
                   'services', 'summary', 'input_sha256'},        # input_sha256 keys the reviews file
    'assessment': {'id', 'created_at', 'state', 'selection', 'stages', 'limits'},
    'iac': {'id', 'target', 'created_at', 'state', 'count', 'findings', 'limits'},
}
# A finding without these cannot be rendered, tagged or (from B1 on) fingerprinted.
FINDING_KEYS = {'code': {'tool', 'rule_id', 'path'},
                'web': {'id'},
                'iac': {'rule_id', 'path', 'severity', 'fingerprint'},
                'repository': {'rule_id', 'fingerprint', 'service_id'}}


def load(name):
    return json.loads((FIXTURES / name).read_text(encoding='utf-8'))


def fixtures():
    return sorted(p for p in FIXTURES.glob('*.json') if p.name != 'MANIFEST.json')


def stage_fixtures(stage):
    """Every frozen report of one stage: oldest, newest and (when it differs) richest."""
    return [(p.stem, json.loads(p.read_text(encoding='utf-8')))
            for p in fixtures() if p.stem.rsplit('-', 1)[0] == stage]


def shape(value, prefix=''):
    """Every key path in the document, mapped to the type names seen there."""
    found = {}
    if isinstance(value, dict):
        for key, item in value.items():
            found.setdefault(f'{prefix}.{key}' if prefix else key, set()).add(type(item).__name__)
            for path, names in shape(item, f'{prefix}.{key}' if prefix else key).items():
                found.setdefault(path, set()).update(names)
    elif isinstance(value, list):
        for item in value:
            for path, names in shape(item, prefix + '[]').items():
                found.setdefault(path, set()).update(names)
    return found


def document_shape(document):
    return {path: sorted(names) for path, names in shape(document).items()}


class SnapshotTests(unittest.TestCase):
    def test_a_fixtures_exist_for_every_stage(self):
        names = {p.name for p in fixtures()}
        for stage in REQUIRED:
            self.assertIn(f'{stage}-oldest.json', names, f'{stage}: eng eski namuna yo‘q')
            self.assertIn(f'{stage}-newest.json', names, f'{stage}: eng yangi namuna yo‘q')

    def test_a2_every_stage_has_a_fixture_with_findings(self):
        """An export path only ever run over an empty report is not being tested."""
        for stage in REQUIRED:
            if stage == 'assessment':
                continue          # its findings live inside stages[], checked in ConsumerTests
            counts = [len(document.get('findings') or []) for _, document in stage_fixtures(stage)]
            self.assertTrue(max(counts, default=0) > 0, f'{stage}: birorta topilmali namuna yo‘q')

    def test_b_key_paths_and_types_match_the_snapshot(self):
        current = {path.name: document_shape(json.loads(path.read_text(encoding='utf-8'))) for path in fixtures()}
        self.assertTrue(SNAPSHOT.is_file(),
                        'shape-snapshot.json yo‘q. Qayta muzlatish: python3 tests/freeze_report_shape.py')
        frozen = json.loads(SNAPSHOT.read_text(encoding='utf-8'))
        self.assertEqual(sorted(frozen), sorted(current), 'namunalar ro‘yxati o‘zgardi')
        for name in sorted(frozen):
            lost = sorted(set(frozen[name]) - set(current[name]))
            self.assertEqual(lost, [], f'{name}: kalit yo‘qoldi yoki nomi o‘zgardi — {lost}')
            changed = {path: (frozen[name][path], current[name][path])
                       for path in frozen[name] if frozen[name][path] != current[name][path]}
            self.assertEqual(changed, {}, f'{name}: maydon turi o‘zgardi')

    def test_c_snapshot_notices_a_renamed_key(self):
        """The guard is only worth having if it actually fires."""
        frozen = json.loads(SNAPSHOT.read_text(encoding='utf-8'))
        mutated = load('code-newest.json')
        mutated['findings_renamed'] = mutated.pop('findings')
        lost = set(frozen['code-newest.json']) - set(document_shape(mutated))
        self.assertIn('findings', lost)


class ContractTests(unittest.TestCase):
    def test_a_required_fields_present_in_every_fixture(self):
        for stage, keys in REQUIRED.items():
            for name, document in stage_fixtures(stage):
                missing = sorted(keys - set(document))
                self.assertEqual(missing, [], f'{name}: {missing} maydonlari yo‘q')

    def test_b_finding_rows_carry_their_identifying_fields(self):
        for stage, keys in FINDING_KEYS.items():
            for name, document in stage_fixtures(stage):
                for finding in document.get('findings') or []:
                    self.assertEqual(sorted(keys - set(finding)), [], f'{name}: {finding.get("rule_id")}')

    def test_c_no_secret_value_survives_in_a_report(self):
        """secret_value is 'hidden' or null by design; a fixture proves it stayed that way."""
        seen = set()

        def walk(value):
            if isinstance(value, dict):
                for key, item in value.items():
                    if key == 'secret_value':
                        seen.add(repr(item))
                    walk(item)
            elif isinstance(value, list):
                for item in value:
                    walk(item)

        for path in fixtures():
            walk(json.loads(path.read_text(encoding='utf-8')))
        self.assertTrue(seen, 'namunalarda birorta gitleaks topilmasi yo‘q — qamrov yo‘qolgan')
        self.assertEqual(seen - {'None', "'hidden'"}, set())


class ConsumerTests(unittest.TestCase):
    """The old reports must still go through every export path unchanged."""

    def test_a_assessment_markdown_and_sarif(self):
        for name, report in stage_fixtures('assessment'):
            with self.subTest(fixture=name):
                self.assertIn(report['id'], pipeline.markdown(report))
                document = pipeline.sarif(report)
                self.assertEqual(document['version'], '2.1.0')
                self.assertTrue(document['runs'])

    def test_b_dependencies_markdown(self):
        for name, report in stage_fixtures('dependencies'):
            with self.subTest(fixture=name):
                self.assertIn(report['id'], dependencies.markdown(report))

    def test_c_web_markdown(self):
        for name, report in stage_fixtures('web'):
            with self.subTest(fixture=name):
                self.assertIn(report['id'], webscan.markdown(report))

    def test_d_repository_sarif(self):
        for name, report in stage_fixtures('repository'):
            with self.subTest(fixture=name):
                document = repository.sarif(report)
                self.assertEqual(document['version'], '2.1.0')
                self.assertEqual(len(document['runs'][0]['results']), len(report['findings']))

    def test_e_verification_summary_over_every_findings_list(self):
        for path in fixtures():
            document = json.loads(path.read_text(encoding='utf-8'))
            summary = verification.summarize(document.get('findings') or [])
            self.assertEqual(summary['total'],
                             summary['confirmed_by_evidence'] + summary['manual_review_required'],
                             path.name)


class LiveShapeTests(unittest.TestCase):
    """A real scan, right now, must still produce the shape that was frozen.

    Everything above compares one file on disk with another, so all of it would
    keep passing while the code that writes reports drifted. This runs the one
    scanner that needs no external binary and takes milliseconds, and checks its
    output against the frozen repository report.
    """

    def setUp(self):
        isolate_triage(self)
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp, True)
        # Never into repository-runs/: the suite-wide evidence guard exists
        # because tests wrote real reports there twice.
        patcher = patch.object(repo_store, 'REPO_RUNS', self.tmp / 'runs')
        patcher.start()
        self.addCleanup(patcher.stop)

    def test_a_live_repository_report_still_has_every_frozen_key(self):
        live = repo_store.scan_profile('chain-demo')
        frozen = document_shape(load('repository-newest.json'))
        current = document_shape(live)
        lost = sorted(path for path in frozen if path not in current)
        self.assertEqual(lost, [], f'jonli hisobotda yo‘qolgan maydonlar: {lost}')
        retyped = {path: (frozen[path], current[path]) for path in frozen
                   if path in current and not set(frozen[path]) & set(current[path])}
        self.assertEqual(retyped, {}, 'jonli hisobotda maydon turi o‘zgardi')

    def test_b_live_report_passes_the_same_contract_and_consumers(self):
        live = repo_store.scan_profile('chain-demo')
        self.assertEqual(sorted(REQUIRED['repository'] - set(live)), [])
        self.assertEqual(repository.sarif(live)['version'], '2.1.0')


if __name__ == '__main__':
    unittest.main()
